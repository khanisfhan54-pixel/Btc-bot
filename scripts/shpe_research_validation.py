def parse_trade_rows() -> List[Dict[str, Any]]:
    path = DATA_DIR / "aggTrades.csv"
    rows: List[Dict[str, Any]] = []
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append(row)
    return rows


def parse_book_rows() -> List[Dict[str, Any]]:
    path = DATA_DIR / "bookDepth.csv"
    rows: List[Dict[str, Any]] = []
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append(row)
    return rows


def audit_timestamps(name: str, timestamps: Sequence[int], expected_step_ms: int | None = None) -> Dict[str, Any]:
    duplicates = len(timestamps) - len(set(timestamps))
    disorder = sum(1 for prev, cur in zip(timestamps, timestamps[1:]) if cur < prev)
    future = [ts for ts in timestamps if ts > CURRENT_TS_MS]
    gaps: List[Dict[str, Any]] = []
    if expected_step_ms is not None:
        unique_sorted = sorted(set(timestamps))
        for prev, cur in zip(unique_sorted, unique_sorted[1:]):
            if cur - prev > expected_step_ms:
                gaps.append({"from": utc_ms(prev), "to": utc_ms(cur), "missing_intervals": int((cur - prev) / expected_step_ms) - 1})
    return {
        "name": name,
        "rows": len(timestamps),
        "start": utc_ms(min(timestamps)) if timestamps else None,
        "end": utc_ms(max(timestamps)) if timestamps else None,
        "duplicates": duplicates,
        "timestamp_disorder": disorder,
        "future_timestamps": len(future),
        "gaps": gaps,
    }


def classify_regime(closes: Sequence[float], idx: int) -> Tuple[str, float, float]:
    window = list(closes[max(0, idx - 11): idx + 1])
    if len(window) < 3:
        return "range", 0.5, 0.0
    rets = [(window[i] - window[i - 1]) / window[i - 1] for i in range(1, len(window)) if window[i - 1] > 0]
    vol = pstdev(rets) if len(rets) > 1 else 0.0
    ma = sum(window) / len(window)
    slope = (window[-1] - window[0]) / max(window[0], 1e-9)
    if vol >= 0.0010:
        return "high_vol", min(1.0, vol / 0.003), vol
    if len(window) >= 12 and vol <= 0.00020:
        return "low_vol", 0.8, vol
    if window[-1] > ma and slope > 0.0005:
        return "trend_up", min(1.0, abs(slope) / 0.004), vol
    if window[-1] < ma and slope < -0.0005:
        return "trend_down", min(1.0, abs(slope) / 0.004), vol
    return "range", 0.6, vol


def build_rows_from_history() -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    trades = parse_trade_rows()
    books = parse_book_rows()
    trade_ts = [int(row["transact_time"]) for row in trades]
    trade_audit = audit_timestamps("data/aggTrades.csv transact_time", trade_ts)

    book_ts: List[int] = []
    book_by_slot: Dict[int, Dict[str, float]] = {}
    for row in books:
        dt = datetime.strptime(row["timestamp"], "%Y-%m-%d %H:%M:%S").replace(tzinfo=timezone.utc)
        ts = int(dt.timestamp() * 1000)
        book_ts.append(ts)
        slot = ts // BAR_MS * BAR_MS
        pct_level = float(row["percentage"])
        notional = float(row["notional"])
        agg = book_by_slot.setdefault(slot, {"bid": 0.0, "ask": 0.0, "events": 0.0})
        if pct_level < 0:
            agg["bid"] += notional
        elif pct_level > 0:
            agg["ask"] += notional
        agg["events"] += 1.0
    book_audit = audit_timestamps("data/bookDepth.csv timestamp", book_ts)

    bars: Dict[int, Dict[str, Any]] = {}
    for row in trades:
        ts = int(row["transact_time"])
        slot = ts // BAR_MS * BAR_MS
        price = float(row["price"])
        quantity = float(row["quantity"])
        bar = bars.setdefault(slot, {"prices": [], "volume": 0.0, "last_trade_ts_ms": 0})
        bar["prices"].append(price)
        bar["volume"] += quantity
        bar["last_trade_ts_ms"] = max(int(bar["last_trade_ts_ms"]), ts)

    bar_slots = sorted(bars)
    bar_gaps = []
    for prev, cur in zip(bar_slots, bar_slots[1:]):
        if cur - prev != BAR_MS:
            bar_gaps.append({"from": utc_ms(prev), "to": utc_ms(cur), "missing_bars": int((cur - prev) / BAR_MS) - 1})

    rows: List[Dict[str, Any]] = []
    closes: List[float] = []
    for slot in bar_slots:
        prices = bars[slot]["prices"]
        close = float(prices[-1])
        closes.append(close)
        idx = len(closes) - 1
        regime, confidence, volatility = classify_regime(closes, idx)
        book = book_by_slot.get(slot, {"bid": 0.0, "ask": 0.0, "events": 0.0})
        depth_total = book["bid"] + book["ask"]
        imbalance = (book["bid"] - book["ask"]) / depth_total if depth_total > 0 else 0.0
        rows.append({
            "symbol": "BTCUSDT",
            "bar_interval": "5m",
            "timestamp_ms": slot,
            "bar_start_ts_ms": slot,
            "bar_end_ts_ms": slot + BAR_MS,
            "feature_available_ts_ms": slot + BAR_MS,
            "open": float(prices[0]),
            "high": float(max(prices)),
            "low": float(min(prices)),
            "close": close,
            "volume": float(bars[slot]["volume"]),
            "last_trade_ts_ms": int(bars[slot]["last_trade_ts_ms"]),
            "book_imbalance": imbalance,
            "depth_replenishment_ratio": 1.0 + min(5.0, depth_total / 10_000_000.0),
            "last_book_event_ts_ms": slot + BAR_MS if book["events"] else slot,
            "regime": regime,
            "regime_timestamp_ms": slot + BAR_MS,
            "regime_confidence": confidence,
            "regime_conviction": confidence,
            "regime_edge_score": 0.0,
            "regime_signal_valid": 1.0,
            "regime_expected_volatility": volatility,
        })

    derived_audit = audit_timestamps("derived 5m OHLCV bars", [int(r["timestamp_ms"]) for r in rows], BAR_MS)
    derived_audit["gaps"] = bar_gaps
    quality_failed = any([
        trade_audit["timestamp_disorder"],
        trade_audit["future_timestamps"],
        book_audit["timestamp_disorder"],
        book_audit["future_timestamps"],
        derived_audit["duplicates"],
        derived_audit["timestamp_disorder"],
        derived_audit["future_timestamps"],
        derived_audit["gaps"],
    ])
    coverage = {
        "sources": [trade_audit, book_audit, derived_audit],
        "quality_failed": bool(quality_failed),
        "missing_sources": ["funding", "open_interest", "liquidations", "regime_history"],
    }
    return rows, coverage


